export type TranslationDictionary = typeof translations.en;

export function getTranslations(lang: string): TranslationDictionary {
  const key = String(lang || "").toLowerCase();
  const available = Object.prototype.hasOwnProperty.call(translations, key);
  const base = translations.en;
  const target: Partial<TranslationDictionary> = available ? (translations[key as keyof typeof translations] as Partial<TranslationDictionary>) : base;

  return {
    ...base,
    ...target,
    pages: { ...base.pages, ...(target.pages ?? {}) },
    legal: { ...base.legal, ...(target.legal ?? {}) },
    home: { ...base.home, ...(target.home ?? {}) },
    actions: target.actions ?? base.actions,
    breadcrumbs: target.breadcrumbs ?? base.breadcrumbs,
    sidebar: target.sidebar ?? base.sidebar,
    errors: target.errors ?? base.errors,
  } as TranslationDictionary;
}

export function useTranslations(lang: string): TranslationDictionary {
  return getTranslations(lang);
}
